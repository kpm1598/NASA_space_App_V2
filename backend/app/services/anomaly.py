"""Isolation Forest anomaly detection on aggregated grid-cell x day features.

Individual hotspots are NOT scored. Observations are aggregated into
0.25-degree grid cells per UTC day with features:
  obs_count, mean_frp, max_frp, viirs_share, night_share
An Isolation Forest (contamination=0.05, random_state=42) flags statistically
unusual cell-days relative to this dataset's own distribution. An anomaly is
NOT a fire, NOT a new fire, and NOT a prediction - the wording everywhere in
this project says exactly that. Explanations are generated by comparing each
feature of the flagged cell-day against its percentile in the full dataset.
"""
import math

import numpy as np
from sklearn.ensemble import IsolationForest
from sklearn.preprocessing import StandardScaler

CELL = 0.25
FEATURES = ["obs_count", "mean_frp", "max_frp", "viirs_share", "night_share"]
LABELS = {
    "obs_count": "observation count",
    "mean_frp": "mean FRP",
    "max_frp": "maximum FRP",
    "viirs_share": "VIIRS share of observations",
    "night_share": "night-time share of observations",
}


def aggregate(conn):
    rows = conn.execute(
        "SELECT latitude, longitude, obs_date, sensor, frp, daynight "
        "FROM observations").fetchall()
    cells = {}
    for r in rows:
        clat = math.floor(r["latitude"] / CELL) * CELL
        clon = math.floor(r["longitude"] / CELL) * CELL
        key = (clat, clon, r["obs_date"])
        c = cells.setdefault(key, {"frps": [], "n": 0, "viirs": 0, "night": 0})
        c["n"] += 1
        if r["frp"] is not None:
            c["frps"].append(r["frp"])
        if r["sensor"] == "VIIRS":
            c["viirs"] += 1
        if (r["daynight"] or "").upper().startswith("N"):
            c["night"] += 1
    out = []
    for (clat, clon, date), c in sorted(cells.items()):
        frps = c["frps"]
        out.append({
            "cell_lat": clat, "cell_lon": clon, "obs_date": date,
            "obs_count": c["n"],
            "mean_frp": float(np.mean(frps)) if frps else 0.0,
            "max_frp": float(np.max(frps)) if frps else 0.0,
            "viirs_share": c["viirs"] / c["n"],
            "night_share": c["night"] / c["n"],
        })
    return out


def _percentile(sorted_vals, v) -> float:
    if len(sorted_vals) == 0:
        return 0.0
    below = int(np.searchsorted(sorted_vals, v, side="right"))
    return 100.0 * below / len(sorted_vals)


def build_explanation(cell, distributions) -> str:
    """Text reasons: the features whose percentile is most extreme (>=90th or
    <=10th), e.g. 'observation count 48 is in the 99th percentile'."""
    reasons = []
    for f in FEATURES:
        pct = _percentile(distributions[f], cell[f])
        if pct >= 90 or pct <= 10:
            val = cell[f]
            val_s = f"{val:.0f}" if f == "obs_count" else f"{val:.2f}"
            reasons.append(
                f"{LABELS[f]} {val_s} is in the {pct:.0f}th percentile "
                f"of all grid-cell days in this dataset")
    if not reasons:
        reasons.append(
            "the combination of features is unusual relative to the "
            "dataset distribution, though no single feature is extreme")
    return ("Statistically unusual grid-cell day (not a confirmed fire and "
            "not a prediction): " + "; ".join(reasons) + ".")


def run_anomaly_detection(conn) -> int:
    conn.execute("DELETE FROM anomalies")
    cells = aggregate(conn)
    if len(cells) < 20:  # too little data for a meaningful forest
        conn.commit()
        return 0
    X = np.array([[c[f] for f in FEATURES] for c in cells], dtype=float)
    Xs = StandardScaler().fit_transform(X)
    model = IsolationForest(contamination=0.05, random_state=42)
    preds = model.fit_predict(Xs)
    scores = model.decision_function(Xs)
    distributions = {f: np.sort(X[:, i]) for i, f in enumerate(FEATURES)}
    n = 0
    for cell, pred, score in zip(cells, preds, scores):
        if pred != -1:
            continue
        conn.execute(
            "INSERT INTO anomalies(cell_lat, cell_lon, obs_date, obs_count, "
            "mean_frp, max_frp, viirs_share, night_share, anomaly_score, "
            "explanation) VALUES (?,?,?,?,?,?,?,?,?,?)",
            (cell["cell_lat"], cell["cell_lon"], cell["obs_date"],
             cell["obs_count"], cell["mean_frp"], cell["max_frp"],
             cell["viirs_share"], cell["night_share"], float(score),
             build_explanation(cell, distributions)))
        n += 1
    conn.commit()
    return n
